create table if not exists public.products (
  id bigint generated by default as identity primary key,
  category text not null, name text not null, price numeric(10,2) not null check (price >= 0),
  description text not null default '', image_url text not null default '', is_popular boolean not null default false,
  is_active boolean not null default true, sort_order integer not null default 100,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.promotions (
  id bigint generated by default as identity primary key,
  title text not null, description text not null default '', image_url text,
  starts_at timestamptz, ends_at timestamptz, is_active boolean not null default true,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  title text not null, body text not null default '', image_url text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
alter table public.products enable row level security;
alter table public.promotions enable row level security;
alter table public.announcements enable row level security;

create policy "Public sees active products" on public.products for select to anon, authenticated using (is_active or auth.jwt() ->> 'email' = 'conectstore.app@gmail.com');
create policy "Admin manages products" on public.products for all to authenticated using (auth.jwt() ->> 'email' = 'conectstore.app@gmail.com') with check (auth.jwt() ->> 'email' = 'conectstore.app@gmail.com');
create policy "Public sees active promotions" on public.promotions for select to anon, authenticated using (is_active and (starts_at is null or starts_at <= now()) and (ends_at is null or ends_at >= now()) or auth.jwt() ->> 'email' = 'conectstore.app@gmail.com');
create policy "Admin manages promotions" on public.promotions for all to authenticated using (auth.jwt() ->> 'email' = 'conectstore.app@gmail.com') with check (auth.jwt() ->> 'email' = 'conectstore.app@gmail.com');
create policy "Public sees active announcements" on public.announcements for select to anon, authenticated using (is_active or auth.jwt() ->> 'email' = 'conectstore.app@gmail.com');
create policy "Admin manages announcements" on public.announcements for all to authenticated using (auth.jwt() ->> 'email' = 'conectstore.app@gmail.com') with check (auth.jwt() ->> 'email' = 'conectstore.app@gmail.com');
grant select on public.products, public.promotions, public.announcements to anon, authenticated;
grant insert, update, delete on public.products, public.promotions, public.announcements to authenticated;
grant usage, select on all sequences in schema public to authenticated;

