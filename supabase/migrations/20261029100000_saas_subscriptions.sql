create or replace function public.save_combo_components(p_combo_product_id bigint,p_components jsonb)
returns void language plpgsql security definer set search_path=public,pg_temp as $$
declare v_component_id bigint;
begin
  if not public.has_active_saas_subscription() then raise exception 'Assinatura inativa. Regularize o pagamento para gerenciar a loja.'; end if;
  if jsonb_typeof(p_components)<>'array' or jsonb_array_length(p_components) not between 1 and 30 then raise exception 'Selecione ao menos um componente para o combo.'; end if;
  perform 1 from public.products where id=p_combo_product_id and category='Combos' for update;
  if not found then raise exception 'Combo não encontrado.'; end if;
  if exists(select 1 from jsonb_array_elements(p_components) e where coalesce((e->>'quantity')::integer,0) not between 1 and 99 or coalesce((e->>'product_id')::bigint,0)<=0 or (e->>'product_id')::bigint=p_combo_product_id) then
    raise exception 'Composição inválida.';
  end if;
  select count(*) into v_component_id from jsonb_array_elements(p_components);
  if (select count(distinct (e->>'product_id')::bigint) from jsonb_array_elements(p_components) e)<>v_component_id then raise exception 'Não repita produtos na composição.'; end if;
  if exists(select 1 from jsonb_array_elements(p_components) e left join public.products p on p.id=(e->>'product_id')::bigint where p.id is null or not p.is_active or p.category='Combos') then
    raise exception 'Os componentes devem ser produtos ativos que não sejam combos.';
  end if;
  delete from public.combo_components where combo_product_id=p_combo_product_id;
  insert into public.combo_components(combo_product_id,component_product_id,quantity_per_combo)
  select p_combo_product_id,(e->>'product_id')::bigint,(e->>'quantity')::integer from jsonb_array_elements(p_components) e;
end $$;
revoke all on function public.save_combo_components(bigint,jsonb) from public,anon;
grant execute on function public.save_combo_components(bigint,jsonb) to authenticated;

create or replace function public.create_counter_sale(p_payment_method text,p_items jsonb)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_items jsonb; v_subtotal numeric(10,2); v_count integer; v_order_id bigint;
begin
  if not public.has_active_saas_subscription() then raise exception 'Assinatura inativa. Regularize o pagamento para registrar vendas.'; end if;
  if p_payment_method not in ('PIX','Cartão','Dinheiro') then raise exception 'Forma de pagamento inválida.'; end if;
  if jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items) not between 1 and 50 then raise exception 'Adicione produtos à venda.'; end if;
  if exists(select 1 from jsonb_array_elements(p_items) e where coalesce((e->>'quantity')::integer,0) not between 1 and 99 or coalesce((e->>'product_id')::bigint,0)<=0) then raise exception 'Quantidade de produto inválida.'; end if;
  select count(*) into v_count from jsonb_array_elements(p_items);
  if (select count(distinct (e->>'product_id')::bigint) from jsonb_array_elements(p_items) e)<>v_count then raise exception 'Há produtos repetidos na venda.'; end if;
  perform public.consume_combo_inventory(p_items);
  select jsonb_agg(jsonb_build_object(
    'product_id',p.id,'name',p.name,'category',p.category,'description',p.description,
    'quantity',(i->>'quantity')::integer,'unit_price',p.price,
    'line_total',p.price*(i->>'quantity')::integer,
    'components',case when p.category='Combos' then coalesce(
      (select jsonb_agg(jsonb_build_object('product_id',component.id,'name',component.name,'quantity',cc.quantity_per_combo) order by component.name)
       from public.combo_components cc join public.products component on component.id=cc.component_product_id
       where cc.combo_product_id=p.id),'[]'::jsonb) else '[]'::jsonb end
  ) order by p.sort_order,p.id),sum(p.price*(i->>'quantity')::integer)
  into v_items,v_subtotal from jsonb_array_elements(p_items) i join public.products p on p.id=(i->>'product_id')::bigint and p.is_active;
  if coalesce(jsonb_array_length(v_items),0)<>v_count then raise exception 'Produto indisponível.'; end if;
  insert into public.orders(customer_name,customer_phone,fulfillment,address,payment_method,notes,items,subtotal,delivery_fee,total,status)
  values('Venda no balcão','','counter','{}'::jsonb,p_payment_method,'Venda presencial no balcão',v_items,v_subtotal,0,v_subtotal,'new')
  returning id into v_order_id;
  return jsonb_build_object('id',v_order_id,'order_number',v_order_id,'items',v_items,'subtotal',v_subtotal,'total',v_subtotal,'payment_method',p_payment_method);
end; $$;
revoke all on function public.create_counter_sale(text,jsonb) from public,anon;
grant execute on function public.create_counter_sale(text,jsonb) to authenticated;

create or replace function public.apply_kiwify_subscription_event(p_event jsonb)
returns text language plpgsql security definer set search_path=public,auth,pg_temp as $$
declare
  v_email text := lower(trim(coalesce(p_event #>> '{Customer,email}',p_event #>> '{customer,email}',p_event->>'email','')));
  v_event_type text := lower(coalesce(p_event->>'webhook_event_type',p_event->>'event_type',''));
  v_event_id text := coalesce(p_event->>'order_id',p_event->>'order_ref',p_event->>'id',concat_ws(':',coalesce(p_event->>'subscription_id',p_event #>> '{Subscription,id}'),coalesce(p_event->>'webhook_event_type',p_event->>'event_type'),coalesce(p_event->>'updated_at',p_event->>'created_at',p_event->>'timestamp')));
  v_subscription_id text := coalesce(p_event #>> '{Subscription,id}',p_event->>'subscription_id');
  v_product_id text := coalesce(p_event #>> '{Product,product_id}',p_event #>> '{product,id}',p_event->>'product_id');
  v_user_id uuid;
  v_plan_id bigint;
  v_status text;
begin
  if coalesce(auth.role(),'') <> 'service_role' then raise exception 'Acesso não autorizado.'; end if;
  if v_event_id is null or v_email = '' then return 'ignored'; end if;
  select id into v_user_id from auth.users where lower(email)=v_email limit 1;
  if v_user_id is null or v_email='conectstore.app@gmail.com' then return 'unmatched'; end if;
  select id into v_plan_id from public.saas_plans where kiwify_product_id=v_product_id and is_active order by id limit 1;
  if v_event_type in ('order_approved','subscription_renewed') or coalesce(p_event->>'order_status','')='paid' then
    v_status := 'active';
  elsif v_event_type in ('subscription_late','subscription_expired') then
    v_status := 'past_due';
  elsif v_event_type in ('subscription_canceled','subscription_cancelled','subscription_cancellation') then
    v_status := 'canceled';
  elsif v_event_type in ('order_refunded','refunded') or coalesce(p_event->>'order_status','')='refunded' then
    v_status := 'refunded';
  elsif v_event_type in ('chargeback','order_chargeback') or coalesce(p_event->>'order_status','')='chargedback' then
    v_status := 'chargeback';
  else
    return 'ignored';
  end if;

  insert into public.kiwify_webhook_events(event_id,event_type)
  values(v_event_id,v_event_type) on conflict do nothing;
  if not found then return 'duplicate'; end if;

  insert into public.saas_subscriptions(user_id,customer_email,plan_id,status,provider_subscription_id,updated_at)
  values(v_user_id,v_email,v_plan_id,v_status,v_subscription_id,now())
  on conflict(user_id) do update set
    customer_email=excluded.customer_email,
    plan_id=coalesce(excluded.plan_id,public.saas_subscriptions.plan_id),
    status=excluded.status,
    provider_subscription_id=coalesce(excluded.provider_subscription_id,public.saas_subscriptions.provider_subscription_id),
    updated_at=now();
  return v_status;
end $$;
revoke all on function public.apply_kiwify_subscription_event(jsonb) from public,anon,authenticated;
grant execute on function public.apply_kiwify_subscription_event(jsonb) to service_role;

