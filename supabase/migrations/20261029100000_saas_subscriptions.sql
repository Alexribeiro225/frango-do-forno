-- SaaS foundation: one store, one subscribed owner, and a separate master administrator.
-- Apply after the existing store migrations.
create table if not exists public.saas_plans (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  price numeric(10,2) not null check (price >= 0),
  billing_interval text not null default 'monthly' check (billing_interval in ('weekly','monthly','bimonthly','quarterly','semiannual','annual')),
  checkout_url text not null,
  kiwify_product_id text,
  features jsonb not null default '[]'::jsonb,
  is_active boolean not null default true,
  sort_order integer not null default 100,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.saas_subscriptions (
  user_id uuid primary key references auth.users(id) on delete cascade,
  plan_id bigint references public.saas_plans(id) on delete set null,
  customer_email text not null,
  status text not null default 'pending' check (status in ('pending','active','past_due','canceled','refunded','chargeback')),
  provider text not null default 'kiwify' check (provider = 'kiwify'),
  provider_subscription_id text,
  current_period_end timestamptz,
  updated_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);
create index if not exists saas_subscriptions_provider_id_idx on public.saas_subscriptions(provider_subscription_id);
create index if not exists saas_subscriptions_email_idx on public.saas_subscriptions(lower(customer_email));

create table if not exists public.kiwify_webhook_events (
  event_id text primary key,
  event_type text not null,
  processed_at timestamptz not null default now()
);

create or replace function public.is_superadmin()
returns boolean language sql stable security definer set search_path = public, auth, pg_temp as $$
  select lower(coalesce(auth.jwt()->>'email','')) = 'conectstore.app@gmail.com';
$$;
create or replace function public.has_active_saas_subscription()
returns boolean language sql stable security definer set search_path = public, auth, pg_temp as $$
  select public.is_superadmin() or exists (
    select 1 from public.saas_subscriptions s
    where s.user_id = auth.uid()
      and s.status = 'active'
      and (s.current_period_end is null or s.current_period_end > now())
  );
$$;
revoke all on function public.is_superadmin() from public;
revoke all on function public.has_active_saas_subscription() from public;
grant execute on function public.is_superadmin() to anon, authenticated;
grant execute on function public.has_active_saas_subscription() to anon, authenticated;

create or replace function public.create_pending_saas_subscription()
returns trigger language plpgsql security definer set search_path = public, auth, pg_temp as $$
declare v_plan_id bigint;
begin
  if lower(coalesce(new.email,'')) <> 'conectstore.app@gmail.com' then
    begin v_plan_id := nullif(new.raw_user_meta_data->>'saas_plan_id','')::bigint;
    exception when others then v_plan_id := null;
    end;
    insert into public.saas_subscriptions(user_id,customer_email,plan_id,status)
    values (new.id,lower(new.email),v_plan_id,'pending')
    on conflict (user_id) do update set customer_email=excluded.customer_email;
  end if;
  return new;
end $$;
revoke all on function public.create_pending_saas_subscription() from public, anon, authenticated;
drop trigger if exists create_pending_saas_subscription on auth.users;
create trigger create_pending_saas_subscription
  after insert on auth.users
  for each row execute function public.create_pending_saas_subscription();

insert into public.saas_subscriptions(user_id,customer_email,status)
select id,lower(email),'pending' from auth.users
where lower(coalesce(email,'')) <> 'conectstore.app@gmail.com'
on conflict (user_id) do nothing;

